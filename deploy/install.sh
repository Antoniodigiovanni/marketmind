#!/usr/bin/env bash
# marketmind — one-command installer for a hardened Linux/systemd host.
#
# Usage (on the host, as root):
#   sudo bash deploy/install.sh
#
# One-liner (repo must be public or mirrored; see README for private repos):
#   curl -fsSL https://raw.githubusercontent.com/Antoniodigiovanni/marketmind/main/deploy/install.sh | sudo bash
#
# Idempotent: rerunning updates the checkout, re-syncs dependencies, refreshes
# the systemd units, and re-runs the DB initialisation.
#
# Overridable env vars:
#   APP_USER     OS user owning the install      (default: marketmind)
#   INSTALL_DIR  install path                    (default: /srv/marketmind)
#   DATA_DIR     data directory                  (default: $INSTALL_DIR/data)
#   BRANCH       git branch/tag to deploy        (default: main)
#   REPO_URL     clone URL                       (default: public GitHub URL)
#   ENV_FILE     path to a secrets .env file     (optional)
#   ENABLE_AUTO_UPDATE  opt into the weekly self-update timer (default: 0)
#
# Persistent config is written to $INSTALL_DIR/deploy.conf on first install;
# install.sh and deploy/update.sh both read it. Edits to the config survive
# reruns and are the single place to pin a branch/tag.
set -euo pipefail

APP_USER="${APP_USER:-marketmind}"
INSTALL_DIR="${INSTALL_DIR:-/srv/marketmind}"
DATA_DIR="${DATA_DIR:-$INSTALL_DIR/data}"
BACKUP_DIR="${BACKUP_DIR:-/srv/marketmind-backups}"
ENV_FILE="${ENV_FILE:-}"
BRANCH_ENV="${BRANCH:-}"
REPO_URL_ENV="${REPO_URL:-}"
ENABLE_AUTO_UPDATE_ENV="${ENABLE_AUTO_UPDATE:-}"
BRANCH="main"
REPO_URL="https://github.com/Antoniodigiovanni/marketmind.git"
ENABLE_AUTO_UPDATE="0"

if [[ -f "$INSTALL_DIR/deploy.conf" ]]; then
  # shellcheck disable=SC1090
  source "$INSTALL_DIR/deploy.conf"
fi
BRANCH="${BRANCH_ENV:-$BRANCH}"
REPO_URL="${REPO_URL_ENV:-$REPO_URL}"
ENABLE_AUTO_UPDATE="${ENABLE_AUTO_UPDATE_ENV:-$ENABLE_AUTO_UPDATE}"

if [[ "$(id -u)" -ne 0 ]]; then
  echo "error: run as root (sudo bash deploy/install.sh)" >&2
  exit 1
fi
if ! command -v systemctl >/dev/null 2>&1; then
  echo "error: systemd is required" >&2
  exit 1
fi

log() { printf '\033[1;34m[marketmind]\033[0m %s\n' "$*"; }

# git runs as root against a repo owned by $APP_USER — declare it safe so the
# ownership guard does not block install/update runs.
if ! git config --global --get safe.directory "$INSTALL_DIR" >/dev/null 2>&1; then
  git config --global --add safe.directory "$INSTALL_DIR"
fi

# 1. App user (system account, no interactive shell)
if ! id "$APP_USER" >/dev/null 2>&1; then
  log "creating system user $APP_USER"
  useradd --system --home-dir "$INSTALL_DIR" --shell /usr/sbin/nologin "$APP_USER"
fi

# 2. Repo checkout / update
if [[ -d "$INSTALL_DIR/.git" ]]; then
  log "updating checkout ($BRANCH)"
  git -C "$INSTALL_DIR" fetch --depth 1 origin "$BRANCH"
  git -C "$INSTALL_DIR" checkout --force "$BRANCH"
  if git -C "$INSTALL_DIR" rev-parse --verify -q "origin/$BRANCH" >/dev/null 2>&1; then
    git -C "$INSTALL_DIR" reset --hard "origin/$BRANCH"
  fi
else
  log "cloning $REPO_URL ($BRANCH)"
  mkdir -p "$INSTALL_DIR"
  git clone --branch "$BRANCH" --depth 1 "$REPO_URL" "$INSTALL_DIR"
fi
mkdir -p "$DATA_DIR" "$INSTALL_DIR/.cache" "$BACKUP_DIR"
chown -R "$APP_USER":"$APP_USER" "$INSTALL_DIR" "$BACKUP_DIR"

if [[ ! -f "$INSTALL_DIR/deploy.conf" ]]; then
  log "writing deploy.conf"
  cat > "$INSTALL_DIR/deploy.conf" <<EOF
# marketmind deploy configuration (generated by install.sh; editable)
BRANCH=$BRANCH
REPO_URL=$REPO_URL
ENABLE_AUTO_UPDATE=$ENABLE_AUTO_UPDATE
EOF
  chown "$APP_USER":"$APP_USER" "$INSTALL_DIR/deploy.conf"
fi

# 3. uv binary (static release, architecture-aware)
if ! command -v uv >/dev/null 2>&1 && [[ ! -x /usr/local/bin/uv ]]; then
  log "installing uv"
  case "$(uname -m)" in
    x86_64)  UV_ARCH="x86_64-unknown-linux-gnu" ;;
    aarch64) UV_ARCH="aarch64-unknown-linux-gnu" ;;
    *) echo "error: unsupported architecture $(uname -m)" >&2; exit 1 ;;
  esac
  tmpdir="$(mktemp -d)"
  curl -fsSL "https://github.com/astral-sh/uv/releases/latest/download/uv-${UV_ARCH}.tar.gz" \
    | tar -xz -C "$tmpdir"
  install -m 0755 "$tmpdir/uv-${UV_ARCH}/uv" /usr/local/bin/uv
  rm -rf "$tmpdir"
fi
export PATH="/usr/local/bin:$PATH"

run_as_app() { # run_as_app <command...>
  sudo -u "$APP_USER" env \
    PATH="$PATH" HOME="$INSTALL_DIR" UV_CACHE_DIR="$INSTALL_DIR/.cache" \
    bash -c 'cd "$1" && shift && exec "$@"' _ "$INSTALL_DIR" "$@"
}

# 4. Dependencies
log "syncing dependencies"
run_as_app uv sync --frozen

# 5. Secrets — never install placeholder values. Enabling the timers with the
# example .env produces a daily job that fails every morning with no signal.
if [[ -n "$ENV_FILE" ]]; then
  install -o "$APP_USER" -g "$APP_USER" -m 0600 "$ENV_FILE" "$INSTALL_DIR/.env"
  log "installed .env from $ENV_FILE"
elif [[ ! -f "$INSTALL_DIR/.env" ]]; then
  cat >&2 <<EOF
error: no secrets file at $INSTALL_DIR/.env

  Create it from the template, set real values, then rerun this installer:

    sudo install -o $APP_USER -g $APP_USER -m 0600 \\
      $INSTALL_DIR/.env.example $INSTALL_DIR/.env
    sudoedit $INSTALL_DIR/.env

  Or point the installer at an existing file:

    sudo ENV_FILE=/path/to/.env bash deploy/install.sh
EOF
  exit 1
else
  log "keeping existing .env"
fi

if grep -qE '^(AI_API_KEY=sk-\.\.\.|FRED_API_KEY=\.\.\.)[[:space:]]*$' "$INSTALL_DIR/.env"; then
  echo "error: $INSTALL_DIR/.env still contains example placeholder values." >&2
  echo "       Set real secrets (AI_API_KEY, FRED_API_KEY) and rerun." >&2
  exit 1
fi

# 6. Database initialisation
log "initialising database"
run_as_app uv run python -m data.db.init

# 7. systemd units
log "installing systemd units"
install -o root -g root -m 0644 \
  "$INSTALL_DIR"/deploy/systemd/*.service \
  "$INSTALL_DIR"/deploy/systemd/*.timer \
  /etc/systemd/system/

# The update script runs as root, so it must not live in a directory the
# service user can write to — that user processes untrusted network input and
# would otherwise be one file write away from root at the next timer firing.
install -o root -g root -m 0755 "$INSTALL_DIR/deploy/update.sh" /usr/local/sbin/marketmind-update

systemctl daemon-reload
systemctl enable --now \
  marketmind-daily.timer \
  marketmind-universe.timer \
  marketmind-backup.timer \
  marketmind-profiles.timer
if [[ "$ENABLE_AUTO_UPDATE" == "1" ]]; then
  log "enabling weekly auto-update timer"
  systemctl enable --now marketmind-update.timer
else
  systemctl disable --now marketmind-update.timer 2>/dev/null || true
fi

# 8. Verification
log "verifying"
systemctl is-active --quiet marketmind-daily.timer \
  || { echo "error: marketmind-daily.timer is not active" >&2; exit 1; }
run_as_app uv run python -m data.db.init >/dev/null
log "done. install dir: $INSTALL_DIR | user: $APP_USER | data: $DATA_DIR"
log "MCP command: cd $INSTALL_DIR && sudo -u $APP_USER env HOME=$INSTALL_DIR \\"
log "             uv run --frozen --no-sync python -m server.mcp"
